import { createDbPlugin } from "@btst/db";

export const calendarSchema = createDbPlugin("calendar", {
	calendarHost: {
		modelName: "calendarHost",
		fields: {
			hostId: { type: "string", required: true, unique: true },
			lockVersion: { type: "string", required: true },
		},
	},
	calendarConnection: {
		modelName: "calendarConnection",
		fields: {
			hostId: { type: "string", required: true },
			connectionKey: { type: "string", required: true, unique: true },
			provider: { type: "string", required: true },
			accountId: { type: "string", required: true },
			label: { type: "string", required: true },
			calendarId: { type: "string", required: false },
			calendarName: { type: "string", required: false },
			status: { type: "string", required: true },
		},
	},
	calendarSync: {
		modelName: "calendarSync",
		fields: {
			hostId: { type: "string", required: true },
			bookingId: { type: "string", required: true },
			connectionId: { type: "string", required: true },
			calendarId: { type: "string", required: true },
			syncKey: { type: "string", required: true, unique: true },
			eventId: { type: "string", required: false },
			state: { type: "string", required: true },
			error: { type: "string", required: false },
			attempts: { type: "number", required: true },
			updatedAt: { type: "date", required: true },
		},
	},
	calendarEventType: {
		modelName: "calendarEventType",
		fields: {
			hostId: { type: "string", required: true },
			slug: { type: "string", required: true, unique: true },
			name: { type: "string", required: true },
			description: { type: "string", required: true },
			location: { type: "string", required: true },
			duration: { type: "number", required: true },
			capacity: { type: "number", required: true },
			waitlistEnabled: { type: "boolean", required: false },
			price: { type: "number", required: false },
			currency: { type: "string", required: false },
			timezone: { type: "string", required: true },
			weeklyAvailability: { type: "string", required: true },
			dateOverrides: { type: "string", required: true },
			limits: { type: "string", required: true },
			active: { type: "boolean", required: true },
			createdAt: { type: "date", required: true },
			updatedAt: { type: "date", required: true },
		},
	},
	calendarWaitlist: {
		modelName: "calendarWaitlist",
		fields: {
			eventTypeId: { type: "string", required: true },
			hostId: { type: "string", required: true },
			eventName: { type: "string", required: true },
			start: { type: "date", required: true },
			end: { type: "date", required: true },
			timezone: { type: "string", required: true },
			name: { type: "string", required: true },
			email: { type: "string", required: true },
			status: { type: "string", required: true },
			token: { type: "string", required: true, unique: true },
			expiresAt: { type: "date", required: true },
			offerExpiresAt: { type: "date", required: false },
			bookingId: { type: "string", required: false },
			createdAt: { type: "date", required: true },
			verifiedAt: { type: "date", required: false },
			offerDelivered: { type: "boolean", required: true },
		},
	},
	calendarBooking: {
		modelName: "calendarBooking",
		fields: {
			eventTypeId: { type: "string", required: true },
			hostId: { type: "string", required: true },
			eventName: { type: "string", required: true },
			start: { type: "date", required: true },
			end: { type: "date", required: true },
			timezone: { type: "string", required: true },
			name: { type: "string", required: true },
			email: { type: "string", required: true },
			status: { type: "string", required: true },
			cancelToken: { type: "string", required: true, unique: true },
			payment: { type: "string", required: false },
			createdAt: { type: "date", required: true },
		},
	},
});
