#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const cliRoot = resolve(scriptDirectory, "..");
const repositoryRoot = resolve(cliRoot, "../..");
const manifestPath = join(cliRoot, "src/utils/legacy-next-render-hashes.ts");
const tsxCli = createRequire(import.meta.url).resolve("tsx/cli");

const aliases = ["@/", "~/", "./"];
const legacyPaths = [
	"app/pages/[[...all]]/page.tsx",
	"app/pages/layout.tsx",
	"app/pages/ssg-blog/page.tsx",
	"app/pages/ssg-blog/[slug]/page.tsx",
	"app/pages/ssg-cms/[typeSlug]/page.tsx",
	"app/pages/ssg-forms/page.tsx",
	"app/pages/ssg-kanban/page.tsx",
];

// These are the only plugin flags read by the immutable historical Next layout
// templates. CMS and Form Builder are included solely to make their conditional
// SSG files available; they do not alter the layout bytes at either ref.
const historicalRenderers = [
	{
		ref: "v3.0.0-rc.2",
		layoutVaryingPluginKeys: [
			"ai-chat",
			"better-auth-ui",
			"blog",
			"kanban",
			"media",
		],
		routeProducerPluginKeys: ["cms", "form-builder"],
	},
	{
		ref: "e9ff9448",
		layoutVaryingPluginKeys: ["ai-chat", "blog", "kanban"],
		routeProducerPluginKeys: ["cms", "form-builder"],
	},
];

async function renderHistoricalHashes(renderer) {
	const checkout = await mkdtemp(join(tmpdir(), "btst-legacy-next-render-"));
	try {
		const archive = execFileSync(
			"git",
			[
				"archive",
				"--format=tar",
				renderer.ref,
				"packages/cli/src",
				"packages/cli/package.json",
			],
			{ cwd: repositoryRoot, maxBuffer: 32 * 1024 * 1024 },
		);
		execFileSync("tar", ["-xf", "-", "-C", checkout], { input: archive });
		await symlink(
			join(cliRoot, "node_modules"),
			join(checkout, "packages/cli/node_modules"),
			"dir",
		);

		const runnerPath = join(checkout, "render-legacy-next.mjs");
		await writeFile(
			runnerPath,
			`import { createHash } from "node:crypto"
import { buildScaffoldPlan } from "./packages/cli/src/utils/scaffold-plan.ts"

const aliases = ${JSON.stringify(aliases)}
const legacyPaths = ${JSON.stringify(legacyPaths)}
const varyingKeys = ${JSON.stringify(renderer.layoutVaryingPluginKeys)}
const routeProducerKeys = ${JSON.stringify(renderer.routeProducerPluginKeys)}
const hashes = new Map(legacyPaths.map((path) => [path, new Set()]))

for (const alias of aliases) {
	for (let mask = 0; mask < 2 ** varyingKeys.length; mask += 1) {
		const selectedKeys = varyingKeys.filter((_, index) => mask & (1 << index))
		const plugins = [...new Set([...routeProducerKeys, ...selectedKeys])]
		const plan = await buildScaffoldPlan({
			framework: "nextjs",
			adapter: "drizzle",
			plugins,
			alias,
			cssFile: "app/globals.css",
		})
		for (const path of legacyPaths) {
			const file = plan.files.find((candidate) => candidate.path === path)
			if (file) {
				hashes.get(path).add(createHash("sha256").update(file.content).digest("hex"))
			}
		}
	}
}

console.log(JSON.stringify(Object.fromEntries(
	[...hashes].map(([path, values]) => [path, [...values].sort()]),
)))
`,
			"utf8",
		);

		return JSON.parse(
			execFileSync(process.execPath, [tsxCli, runnerPath], {
				cwd: checkout,
				encoding: "utf8",
				maxBuffer: 32 * 1024 * 1024,
			}),
		);
	} finally {
		await rm(checkout, { recursive: true, force: true });
	}
}

function formatManifest(hashes) {
	const lines = [
		"// Generated by scripts/generate-legacy-next-render-hashes.mjs from exact",
		"// buildScaffoldPlan() bytes at v3.0.0-rc.2 and e9ff9448 across every",
		"// supported plugin selection and import alias. Consumer edits therefore",
		"// remain outside the allowlist and fail closed.",
		"export const LEGACY_NEXT_RENDER_HASHES = {",
	];
	for (const path of legacyPaths) {
		lines.push(`\t${JSON.stringify(path)}: [`);
		for (const hash of hashes[path]) lines.push(`\t\t${JSON.stringify(hash)},`);
		lines.push("\t],");
	}
	lines.push("} as const;", "");
	return lines.join("\n");
}

const combinedHashes = Object.fromEntries(
	legacyPaths.map((path) => [path, new Set()]),
);
for (const renderer of historicalRenderers) {
	const renderedHashes = await renderHistoricalHashes(renderer);
	for (const path of legacyPaths) {
		for (const hash of renderedHashes[path]) combinedHashes[path].add(hash);
	}
}

const output = formatManifest(
	Object.fromEntries(
		legacyPaths.map((path) => [path, [...combinedHashes[path]].sort()]),
	),
);

if (process.argv.includes("--check")) {
	const current = await readFile(manifestPath, "utf8");
	if (current !== output) {
		console.error(
			"Legacy Next render hashes drifted. Run `pnpm legacy-next-hashes:generate` and review the historical byte changes.",
		);
		process.exitCode = 1;
	}
} else {
	await writeFile(manifestPath, output, "utf8");
}
